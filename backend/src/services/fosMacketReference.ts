/** Catalogue entry for an instrument named in §9, matched the same stem-aware
 *  way the linkage check matches instrument names. Null when the макет has no
 *  entry for it — a кафедра may legitimately use an instrument the макет never
 *  listed, and inventing a description for it would be worse than omitting one. */
export function catalogueEntryFor(instrument: string): FosCatalogueRow | null {
  return MACKET_INSTRUMENT_CATALOGUE.find(
    (r) => mentions(r.name, instrument) || mentions(instrument, r.name),
  ) ?? null
}
